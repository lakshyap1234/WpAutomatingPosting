<?php
/**
 * Writes the Connector's config/agency.php (see bin/build.sh), from a build profile
 * (PROFILE=visiby: bin/profiles/visiby.php) or from AGENCY_URL, AGENCY_NAME and
 * AGENCY_LOGO (an agency using the Content Publisher plugin).
 * The same settings always give the same file.
 */

function fail( string $message ): void {
	fwrite( STDERR, $message . "\n" );
	exit( 1 );
}

// Plain HTTP only to this computer (a test tool, RFC 8252), and only in this profile.
const LOOPBACK_PROFILE = 'local';

$profile = (string) getenv( 'PROFILE' );
if ( '' !== $profile ) {
	$file = __DIR__ . '/profiles/' . $profile . '.php';
	if ( ! preg_match( '~^[a-z0-9-]+$~', $profile ) || ! is_file( $file ) ) {
		$known = array_map( fn( $f ) => basename( $f, '.php' ), glob( __DIR__ . '/profiles/*.php' ) );
		fail( "Unknown build profile \"$profile\" (known: " . implode( ', ', $known ) . ')' );
	}
	$config = require $file;
} else {
	$url    = rtrim( (string) getenv( 'AGENCY_URL' ), '/' );
	$config = array(
		'client_id'     => 'cpub-publisher',
		'name'          => (string) getenv( 'AGENCY_NAME' ),
		'url'           => $url,
		'logo'          => (string) getenv( 'AGENCY_LOGO' ),
		'redirect_uris' => array( $url . '/wp-admin/admin.php?page=cpub-publisher&cpub_oauth=callback' ),
	);
}

if ( ! preg_match( '~^[a-z0-9._-]+$~', (string) ( $config['client_id'] ?? '' ) ) ) {
	fail( 'client_id must be letters, digits, ".", "_" or "-"' );
}
if ( '' === trim( (string) ( $config['name'] ?? '' ) ) ) {
	fail( 'name must not be empty' );
}
if ( ! preg_match( '~^https://[a-z0-9.-]+(:\d+)?(/[^?#]*)?$~i', (string) ( $config['url'] ?? '' ) ) ) {
	fail( 'AGENCY_URL (url) must be an https:// address without query or fragment, got: ' . ( $config['url'] ?? '' ) );
}
$logo = (string) ( $config['logo'] ?? '' );
if ( '' !== $logo && ! preg_match( '~^(https://[^\s"\'<>]+|[A-Za-z0-9._-]+\.(png|jpe?g|gif|svg|webp))$~i', $logo ) ) {
	fail( "AGENCY_LOGO (logo) must be an image file name in content-publisher-connector/assets/ or an https:// address, got: $logo" );
}
if ( '' !== $logo && ! str_starts_with( $logo, 'https://' ) && ! is_file( dirname( __DIR__ ) . '/content-publisher-connector/assets/' . $logo ) ) {
	fail( "The logo $logo is not in content-publisher-connector/assets/ (the consent screen would show no logo)" );
}
$redirects = array_values( (array) ( $config['redirect_uris'] ?? array() ) );
if ( ! $redirects ) {
	fail( 'redirect_uris must not be empty' );
}
foreach ( $redirects as $uri ) {
	if ( preg_match( '~^https://[a-z0-9.-]+(:\d+)?/[^#\s]*$~i', $uri ) ) {
		continue;
	}
	if ( 'http://127.0.0.1/callback' === $uri ) {
		if ( LOOPBACK_PROFILE !== $profile ) {
			fail( "The loopback return address $uri is only allowed in the \"" . LOOPBACK_PROFILE . '" profile' );
		}
		continue;
	}
	fail( "Return addresses must be https:// (no fragment), got: $uri" );
}

$config = array(
	'client_id'     => (string) $config['client_id'],
	'name'          => (string) $config['name'],
	'url'           => (string) $config['url'],
	'logo'          => $logo,
	'redirect_uris' => $redirects,
);
$source = '' !== $profile ? "bin/build.sh config $profile" : 'bin/build.sh config';
echo "<?php\n/**\n * The one agency this Connector trusts. Generated by bin/build.sh ($source);\n * don't edit by hand.\n *\n * @package CPub\\Connector\n */\n\nreturn " . var_export( $config, true ) . ";\n";
