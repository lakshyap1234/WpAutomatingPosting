<?php
/**
 * Writes the Connector's config/agency.php from environment variables (see bin/build.sh).
 * The same settings always give the same file.
 */

$url = rtrim( (string) getenv( 'AGENCY_URL' ), '/' );
if ( ! preg_match( '~^https://[a-z0-9.-]+(:\d+)?(/[^?#]*)?$~i', $url ) ) {
	fwrite( STDERR, "AGENCY_URL must be an https:// address without query or fragment, got: $url\n" );
	exit( 1 );
}
$logo = (string) getenv( 'AGENCY_LOGO' );
if ( '' !== $logo && ! preg_match( '~^(https://[^\s"\'<>]+|[A-Za-z0-9._-]+\.(png|jpe?g|gif|svg|webp))$~i', $logo ) ) {
	fwrite( STDERR, "AGENCY_LOGO must be an image file name in content-publisher-connector/assets/ or an https:// address, got: $logo\n" );
	exit( 1 );
}
$redirects = array( $url . '/wp-admin/admin.php?page=cpub-publisher&cpub_oauth=callback' );
if ( '1' === getenv( 'DEMO' ) ) {
	$redirects[] = 'http://127.0.0.1/callback';
}
$config = array(
	'client_id'     => 'cpub-publisher',
	'name'          => (string) getenv( 'AGENCY_NAME' ),
	'url'           => $url,
	'logo'          => $logo,
	'redirect_uris' => $redirects,
);
echo "<?php\n/**\n * The one agency this Connector trusts. Generated by bin/build.sh (bin/build.sh config);\n * don't edit by hand.\n *\n * @package CPub\\Connector\n */\n\nreturn " . var_export( $config, true ) . ";\n";
